    public static IReadOnlyDictionary<string, string> ClientStrings(HttpContext context) =>
        ClientKeys.ToDictionary(key => key, key => T(context, key));

    public static string T(HttpContext context, string key, string? ru = null)
    {
        var lang = context.Request.Cookies["lang"];
        var dictionary = lang == "en" ? En : Ru;
        if (dictionary.TryGetValue(key, out var value))
        {
            return value;
        }

        if (Ru.TryGetValue(key, out var ruValue))
        {
            return lang == "en" ? key : ruValue;
        }

        return ru ?? key;
    }

    public static string ForLanguage(string language, string key) =>
        (language == "en" ? En : Ru).TryGetValue(key, out var value) ? value : key;

    public static string Status(HttpContext context, string status)
    {
        var lang = context.Request.Cookies["lang"];

        return status switch
        {
            Models.TicketStatuses.New => lang == "en" ? "New" : "Новый",
            Models.TicketStatuses.BotAnswered => lang == "en" ? "Bot answered" : "Ответ бота",
            Models.TicketStatuses.WaitingForOperator => lang == "en" ? "Waiting for operator" : "Ждёт оператора",
            Models.TicketStatuses.InProgress => lang == "en" ? "In progress" : "В работе",
            Models.TicketStatuses.Closed => lang == "en" ? "Closed" : "Закрыт",
            _ => status
        };
    }

    public static string RequestCountLabel(HttpContext context, int count)
    {
        if (context.Request.Cookies["lang"] == "en")
        {
            return T(context, count == 1 ? "RequestOne" : "RequestCount");
        }

        var lastTwo = count % 100;
        if (lastTwo is >= 11 and <= 14) return T(context, "RequestCount");
        return (count % 10) switch
        {
            1 => T(context, "RequestOne"),
            >= 2 and <= 4 => T(context, "RequestFew"),
            _ => T(context, "RequestCount")
        };
    }

    public static string LanguageName(HttpContext context, string? value)
    {
        var normalized = ChatTranslationService.NormalizeLanguage(value);
        return normalized switch
        {
            "Русский" or "Russian" => T(context, "RussianLanguage"),
            "English" => T(context, "EnglishLanguage"),
            _ => normalized
        };
    }
